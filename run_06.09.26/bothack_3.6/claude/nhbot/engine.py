"""Client for the patched NetHack 3.6.7 "bot" window port.

One `Engine` = one game process in its own directory.  The engine speaks the
JSON-lines protocol documented in engine/nethack-3.6.7/win/bot/winbot.c:
every input the game needs arrives as a request (`Request`), and exactly one
answer line is written back.

The engine keeps the accumulated observation (map, status, inventory) so the
caller only deals with requests.  Evaluation-only data (`priv`, the end
verdict) is kept apart from what a policy should see.
"""
